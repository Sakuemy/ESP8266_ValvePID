#pragma once
/*
 * TimeManager.h
 * -----------------------------------------------------------------
 * Получение и поддержание текущего времени:
 *  - синхронизация по NTP при наличии интернета;
 *  - при отсутствии сети - расчёт времени на основе millis() от последней
 *    успешной синхронизации (или от старта устройства, если синхронизации
 *    ещё не было ни разу);
 *  - настраиваемое смещение часового пояса (settings.time.gmtOffsetSec),
 *    применяется без перезагрузки через applySettings().
 * -----------------------------------------------------------------
 */

#include "Config.h"

namespace TimeManager {

// gmtOffsetSec - начальное смещение от UTC в секундах (settings.time.gmtOffsetSec).
void begin(int32_t gmtOffsetSec);

// Применить новое смещение часового пояса без перезагрузки (пересинхронизация
// продолжится с уже накопленным NTP-временем - меняется только то, как оно
// переводится в "локальные" секунды).
void applySettings(int32_t gmtOffsetSec);

// Вызывать часто из loop(); сама решает, когда пора (пере)синхронизироваться.
void update(bool wifiConnected);

// Текущее unix-время (секунды) С УЧЁТОМ настроенного смещения часового
// пояса, с использованием NTP либо оценки по millis().
uint32_t now();

// Была ли хоть раз успешная синхронизация с момента включения.
bool hasSyncedOnce();

// Секунд с последней успешной синхронизации (для отображения в UI/диагностике).
uint32_t secondsSinceLastSync();

} // namespace TimeManager
