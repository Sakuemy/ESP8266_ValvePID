#pragma once
/*
 * Storage.h
 * -----------------------------------------------------------------
 * Хранение всех пользовательских настроек (ПИД, сервопривод, сеть)
 * в энергонезависимой памяти через LittleFS в виде JSON-файла.
 *
 * Также отвечает за пароль администратора: пароль в открытом виде
 * никогда не сохраняется на диск и не должен нигде сравниваться
 * напрямую - только через verifyPassword()/setPassword() ниже
 * (SHA-256 от соль+пароль, соль случайна и уникальна для устройства).
 * -----------------------------------------------------------------
 */

#include "Config.h"

namespace Storage {

// Инициализировать файловую систему (вызывать один раз в setup()).
bool begin();

// Загрузить настройки из /config.json. Если файла нет или он повреждён —
// заполняет settings значениями по умолчанию и сохраняет их на диск.
// Также прозрачно мигрирует файлы старого формата (открытый пароль) на
// хэш+соль при первой загрузке.
bool load(AppSettings &settings);

// Сохранить настройки. Возвращает true при успехе.
bool save(const AppSettings &settings);

// Проверить пароль (в открытом виде, как ввёл пользователь) против
// сохранённых хэша+соли в settings.admin. true - пароль верный.
bool verifyPassword(const AppSettings &settings, const char *password);

// Установить новый пароль: генерирует новую случайную соль, считает
// SHA-256(соль+пароль) и записывает hash+salt в settings.admin.
// Вызывающий код должен сам сохранить settings через Storage::save(),
// если изменение должно пережить перезагрузку.
void setPassword(AppSettings &settings, const char *newPassword);

} // namespace Storage
