#pragma once
/*
 * TempHistory.h
 * -----------------------------------------------------------------
 * Кольцевой буфер точек температуры за последние 24 часа.
 * Хранится ТОЛЬКО в оперативной памяти (не пишется в Flash, чтобы не
 * изнашивать её частыми записями) - переживает перезагрузку СТРАНИЦЫ в
 * браузере (график просто заново запрашивает /api/history у устройства),
 * но не переживает перезагрузку/потерю питания самого устройства - это
 * осознанный выбор.
 * -----------------------------------------------------------------
 */

#include "Config.h"

namespace TempHistory {

void begin();

// Вызывать часто из loop(); сама решает, пора ли добавить новую точку
// (раз в HISTORY_INTERVAL_MS), используя currentUnixTime как метку времени.
// valvePercent - текущее открытие крана (%): между точками оно усредняется,
// поэтому на графике видна реальная работа сервопривода за интервал, а не
// случайное мгновенное значение.
void update(float temperature, float valvePercent, uint32_t currentUnixTime);

// Сериализовать историю в компактный JSON-массив
// [{"t":unixtime,"v":temp,"s":valve%}, ...] в порядке от старой к новой точке.
// Возвращает количество точек.
size_t serializeToJson(String &out);

size_t count();

} // namespace TempHistory
