#pragma once
/*
 * TempSensor.h
 * -----------------------------------------------------------------
 * Неблокирующая обёртка над DS18B20 (через OneWire/DallasTemperature).
 * Конвертация запускается асинхронно (setWaitForConversion(false)),
 * что не даёт занять процессор блокирующей задержкой ~750ms.
 * -----------------------------------------------------------------
 */

#include "Config.h"

namespace TempSensor {

// Инициализация шины и датчика. Возвращает true, если датчик найден.
bool begin();

// Вызывать часто из loop(). Сам решает, когда пора запросить новую
// конвертацию и когда пора считать результат.
void update();

// Последняя валидная температура. Если датчик ещё не дал ни одного
// успешного чтения — вернёт NAN.
float getTemperature();

// true, если хотя бы одно успешное чтение уже было получено.
bool isValid();

} // namespace TempSensor
