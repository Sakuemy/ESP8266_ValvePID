#pragma once
/*
 * ValveServo.h
 * -----------------------------------------------------------------
 * Управление сервоприводом шарового крана. Отвечает за:
 *  - преобразование желаемого % открытия в импульс (мкс) сервопривода;
 *  - ограничение диапазона min/max % открытия из настроек;
 *  - плавное обновление позиции не чаще SERVO_UPDATE_INTERVAL_MS,
 *    ограниченное шагом SERVO_MAX_STEP_PERCENT_PER_UPDATE за такт,
 *    чтобы не дёргать сервопривод слишком часто и не рывком.
 * -----------------------------------------------------------------
 */

#include "Config.h"

namespace ValveServo {

void begin(const ServoSettings &settings);

// Применить новые настройки сервопривода (калибровка импульсов, лимиты).
void applySettings(const ServoSettings &settings);

// Задать желаемый % открытия (0..100). Реальное значение будет
// ограничено minPercent/maxPercent из настроек.
// Пока активен ручной тестовый режим (см. setManualOverride), вызовы этой
// функции игнорируются - так ПИД-регулятор не "перетягивает" кран обратно
// во время ручного теста угла открытия.
void setTargetPercent(double percent);

// ---------------------- Тестовый (ручной) режим ----------------------
// Позволяет временно управлять краном вручную (например, из меню на
// дисплее), не боясь, что очередной такт ПИД-регулятора тут же вернёт
// кран в "рабочее" положение.
//
// Включить: setManualOverride(true), затем крутить угол через
// setManualPercent(). Выключить: setManualOverride(false) - управление
// вернётся к ПИД-регулятору с его следующего такта.
void setManualOverride(bool active);
bool isManualOverrideActive();

// Задать % открытия напрямую в ручном тестовом режиме, минуя проверку
// setTargetPercent() на активность ручного режима. Действует независимо
// от того, включён ли setManualOverride (но вызывать имеет смысл только
// когда он включён - иначе следующий такт ПИД перезапишет значение).
void setManualPercent(double percent);

// Вызывать часто из loop() - применяет целевое положение не чаще,
// чем раз в SERVO_UPDATE_INTERVAL_MS, снижая износ и рывки серво.
void update();

// Текущее фактически выставленное % открытия (после ограничений).
double getCurrentPercent();

} // namespace ValveServo
