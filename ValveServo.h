#pragma once
/*
 * ValveServo.h
 * -----------------------------------------------------------------
 * Управление сервоприводом шарового крана. Отвечает за:
 *  - преобразование желаемого % открытия в импульс (мкс) сервопривода;
 *  - ограничение диапазона min/max % открытия из настроек;
 *  - плавное обновление позиции не чаще SERVO_UPDATE_INTERVAL_MS,
 *    ограниченное шагом SERVO_MAX_STEP_PERCENT_PER_UPDATE за такт,
 *    чтобы не дёргать сервопривод слишком часто и не рывком;
 *  - режимы, отключающие ПИД: ручной (меню на дисплее / веб),
 *    предпросмотр min/max при настройке и тест хода мин<->макс.
 * -----------------------------------------------------------------
 */

#include "Config.h"

namespace ValveServo {

// Режим управления краном.
enum class Mode : uint8_t {
    AUTO = 0,    // кран ведёт ПИД-регулятор
    MANUAL,      // ручное управление (меню на дисплее / веб); ограничено min/max из настроек
    PREVIEW,     // предпросмотр редактируемого min/max: серва идёт на это значение (0..100, без min/max)
    RANGE_TEST   // автоматический тест хода: мин -> макс -> мин
};

void begin(const ServoSettings &settings);

// Применить новые настройки сервопривода (калибровка импульсов, лимиты).
// Заканчивает предпросмотр калибровки: сохранённые значения становятся рабочими.
void applySettings(const ServoSettings &settings);

// ---------------------- Аварийное закрытие ----------------------
// Вызывать каждый цикл из loop(): active = true, если нет валидных данных
// датчика температуры ИЛИ критически разряжена батарея. Пока флаг взведён:
//  - целевое положение = minPercent из настроек в ЛЮБОМ режиме (ПИД, ручной,
//    предпросмотр, тест) - ход по-прежнему плавный, не быстрее
//    SERVO_MAX_STEP_PERCENT_PER_UPDATE за такт;
//  - идущие ручной режим/предпросмотр/тест прерываются (кран -> AUTO);
//  - новые ручной режим/предпросмотр/тест не запускаются (см. возвраты ниже).
// Когда флаг снят, обычная логика возвращается сама.
void setSafetyClose(bool active);
bool isSafetyClose();

// Задать желаемый % открытия (0..100) от ПИД. Реальное значение будет
// ограничено minPercent/maxPercent из настроек. Игнорируется, пока кран
// НЕ в режиме AUTO (ручной режим/предпросмотр/тест) - так ПИД не
// "перетягивает" кран обратно.
void setTargetPercent(double percent);

// ---------------------- Ручной режим ----------------------
// Включить/выключить ручное управление. timeoutMs > 0 - через столько мс без
// новых команд (setManualPercent) кран сам вернётся в AUTO (защита от
// "забытого" ручного режима); 0 - без тайм-аута (так работает тест на дисплее).
// Возвращает false, если включить ручной режим нельзя (активно аварийное
// закрытие); выключение (active = false) всегда возвращает true.
bool setManualOverride(bool active, unsigned long timeoutMs = 0);

// true, если кран НЕ под управлением ПИД (ручной режим, предпросмотр или
// тест хода) - main loop в это время не считает ПИД.
bool isManualOverrideActive();

// Задать % открытия напрямую в ручном режиме (ограничивается min/max из
// настроек). Обновляет таймер тайм-аута ручного режима. Вне ручного режима
// игнорируется - иначе запоздавшая команда перебила бы цель ПИД.
void setManualPercent(double percent);

// ---------------------- Предпросмотр min/max ----------------------
// Плавно повернуть серву на указанный % (0..100) БЕЗ учёта текущих min/max -
// чтобы при настройке границ хода серва сразу показывала, где будет край.
// Сам режим сбрасывается в AUTO через VALVE_PREVIEW_TIMEOUT_MS после
// последнего вызова либо явно через endPreview().
// Возвращает false (и ничего не делает), если идёт тест хода или активно
// аварийное закрытие.
bool previewPercent(double percent);
void endPreview(); // завершить предпросмотр (только если он активен)

// ---------------------- Предпросмотр калибровки импульсов ----------------------
// Сразу применить редактируемые (ещё не сохранённые) импульсы «закрыто»/
// «открыто», мкс. Допустимо 500..2500 мкс, разница не менее
// SERVO_MIN_PULSE_SPAN_US, иначе возвращается false и ничего не меняется.
// Выходной импульс сдвигается к новому значению плавно - не быстрее
// SERVO_MAX_STEP_PERCENT_PER_UPDATE (от нового размаха импульса) за такт.
// Если значения не подтверждались (повторный вызов) дольше
// VALVE_PREVIEW_TIMEOUT_MS или вызван endCalibrationPreview(), откатывается
// к сохранённым. applySettings() делает применённые значения постоянными.
bool previewCalibration(uint16_t closedPulseUs, uint16_t openPulseUs);
void endCalibrationPreview();

// ---------------------- Тест хода мин <-> макс ----------------------
// Запустить тест: серва едет в minP, пауза, в maxP, пауза, обратно в minP,
// затем кран возвращается в AUTO. minP/maxP - могут быть ещё не сохранённые
// значения из формы. Возвращает false, если minP >= maxP.
// Также возвращает false при активном аварийном закрытии.
bool startRangeTest(double minP, double maxP);
void stopRangeTest(); // прервать тест, вернуть AUTO
bool isRangeTestActive();
// Этап теста: 0 - не идёт, 1 - к минимуму, 2 - к максимуму, 3 - возврат к минимуму.
uint8_t getRangeTestStage();

// Вызывать часто из loop() - применяет целевое положение не чаще,
// чем раз в SERVO_UPDATE_INTERVAL_MS, снижая износ и рывки серво.
void update();

// Текущее фактически выставленное % открытия.
double getCurrentPercent();
// Целевое % открытия (куда сервопривод движется).
double getTargetPercent();

Mode getMode();
const char *getModeName(); // "auto" / "manual" / "preview" / "test"
// Сколько секунд осталось до автоматического возврата в AUTO (0 - тайм-аута нет).
uint32_t getModeRemainingSec();

} // namespace ValveServo
