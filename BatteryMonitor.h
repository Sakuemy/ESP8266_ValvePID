#pragma once
/*
 * BatteryMonitor.h
 * -----------------------------------------------------------------
 * Измерение напряжения батареи через встроенный АЦП (A0) ESP8266,
 * пересчёт в проценты заряда по калибровочным точкам 0%/100% из
 * настроек, и определение "батарея не подключена".
 * -----------------------------------------------------------------
 */

#include "Config.h"

namespace BatteryMonitor {

void begin(const BatterySettings &settings);

// Применить новые калибровочные точки (0%/100%) без перезагрузки.
void applySettings(const BatterySettings &settings);

// Вызывать часто из loop(); сама решает, когда пора сделать очередное
// (усреднённое) измерение - не чаще BATTERY_READ_INTERVAL_MS.
void update();

// Последнее измеренное напряжение батареи, В (с учётом делителей).
float getVoltage();

// Заряд в процентах (0..100), рассчитанный линейно между калибровочными
// точками. Если батарея не подключена, значение не имеет смысла -
// проверяйте isConnected() отдельно.
float getPercent();

// true, если измеренное напряжение выше порога "отключено"
// (BATTERY_DISCONNECT_THRESHOLD_V).
bool isConnected();

} // namespace BatteryMonitor
